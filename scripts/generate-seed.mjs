// Generates the Supabase seed migration from src/data/questions.js
//   npm run seed:sql
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'
import { questions } from '../src/data/questions.js'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const out = join(root, 'supabase/migrations/20261028000002_seed_questions.sql')

const lit = (v) => (v == null ? 'null' : `'${String(v).replace(/'/g, "''")}'`)

const required = ['id', 'category', 'text', 'options', 'correct', 'explanation', 'difficulty']
const ids = new Set()
for (const q of questions) {
  for (const k of required) if (q[k] == null) throw new Error(`${q.id}: missing ${k}`)
  if (ids.has(q.id)) throw new Error(`duplicate id ${q.id}`)
  ids.add(q.id)
  if (q.correct < 0 || q.correct >= q.options.length) throw new Error(`${q.id}: bad correct index`)
}

const rows = questions.map(
  (q) =>
    `  (${lit(q.id)}, ${lit(q.category)}, ${lit(q.text)}, ${lit(q.code)}, ${lit(q.language)}, ` +
    `${lit(JSON.stringify(q.options))}::jsonb, ${q.correct}, ${lit(q.explanation)}, ${lit(q.difficulty)})`
)

const sql = `-- GENERATED by scripts/generate-seed.mjs — edit src/data/questions.js and re-run \`npm run seed:sql\`.
insert into public.questions (id, category, text, code, language, options, correct_index, explanation, difficulty) values
${rows.join(',\n')}
on conflict (id) do update set
  category = excluded.category, text = excluded.text, code = excluded.code, language = excluded.language,
  options = excluded.options, correct_index = excluded.correct_index,
  explanation = excluded.explanation, difficulty = excluded.difficulty;
`
writeFileSync(out, sql)
console.log(`Wrote ${questions.length} questions to ${out}`)
